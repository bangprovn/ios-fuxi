#!/usr/bin/env python3
"""Compile Linux ath12k on FreeBSD LinuxKPI headers plus xnu/fuxi-ath12k/compat.

Link check of the driver domain (design: research_notes/wifi-ath12k-port.md,
sections 1, 3, 5; milestone M0). Inputs are two sparse source trees that stay
outside git: Linux at ATH12K_LINUX_SHA and FreeBSD at LKPI_FREEBSD_SHA, both
treated as data. Nothing inside them runs, including the FreeBSD awk generators:
the few headers its build would generate are generated here.

Steps, each of which stops the build when it fails:
  1. the pins and tree digests match tools/ci/pins.env;
  2. license gate: all compiled ath12k files are BSD-3-Clause-Clear, no path
     under the Linux tree outside the ath12k directory is on the include path;
  3. tools/ath12k-edits.json applies, every edit matching exactly once;
  4. all sources compile with PAGE_SIZE 4096 asserted (design R2);
  5. the dependency files show that only allowed files were read;
  6. one relocatable object results;
  7. each undefined symbol is on tools/ath12k-undefined-allow.json.

On macOS with Xcode, step 6 is `ld -r`. ld.lld cannot write a relocatable Mach-O,
so elsewhere the same Mach-O targeted sources are compiled to bitcode, merged by
llvm-link, internalized and turned into one Mach-O object by llc.
"""
import argparse
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys

REPO = Path(__file__).resolve().parents[2]
PINS = REPO / 'tools/ci/pins.env'
EDITS = REPO / 'tools/ath12k-edits.json'
ALLOW = REPO / 'tools/ath12k-undefined-allow.json'
OWN = REPO / 'xnu/fuxi-ath12k'

ATH12K = 'drivers/net/wireless/ath/ath12k'
SPDX = 'SPDX-License-Identifier: BSD-3-Clause-Clear'
# Design section 1: 33 files. wifi7/mhi.c is data tables only.
DRIVER = tuple(f'{n}.c' for n in (
    'core hal wmi mac reg htc dp dp_tx dp_rx dp_htt dp_peer debug ce peer dbring dp_mon fw p2p'
).split()) + tuple(f'wifi7/{n}.c' for n in (
    'core ce dp dp_mon dp_rx dp_tx hal hal_rx hal_tx hal_wcn7850 hal_qcn9274 hal_qcc2072 hw wmi mhi'
).split())
# Generated by FreeBSD's makeobjops.awk there; generated from the .m text here.
KOBJ = ('kern/device_if.m', 'kern/bus_if.m', 'dev/pci/pci_if.m', 'dev/pci/pci_iov_if.m',
        'dev/pci/pcib_if.m', 'dev/iicbus/iicbus_if.m', 'dev/iicbus/iicbb_if.m',
        'dev/backlight/backlight_if.m', 'dev/usb/usb_if.m', 'dev/ofw/ofw_bus_if.m')
# Design section 5: only these paths are ever fetched.
LINUX_URL = 'https://github.com/gregkh/linux.git'
FREEBSD_URL = 'https://github.com/freebsd/freebsd-src.git'
LINUX_SPARSE = (f'/{ATH12K}/',)
FREEBSD_SPARSE = ('/COPYRIGHT',) + tuple(f'/sys/{d}/' for d in (
    'compat/linuxkpi sys arm64/include net net80211 netinet netinet6 vm kern tools libkern ddb security '
    'fs/pseudofs crypto opencrypto geom bsm isa cam rpc xdr x86/include ofed/include dev/pci dev/ofw dev/fdt '
    'dev/acpica dev/usb dev/iicbus dev/backlight contrib/ck/include contrib/dev/acpica/include contrib/libnv'
).split())
EXPORTED_PREFIX = 'fa_'
TARGET = 'arm64-apple-macos13'
CFLAGS = ('-mkernel -mgeneral-regs-only -fno-builtin -fno-common -ffreestanding -fno-strict-aliasing '
          '-funsigned-char -nostdinc -std=gnu17 -O2 -w -ferror-limit=0 '
          '-Werror=implicit-function-declaration -Werror=int-conversion '
          '-Werror=incompatible-function-pointer-types -Werror=return-type '
          '-D__FreeBSD__=15 -D_KERNEL -DKLD_MODULE -DHAVE_KERNEL_OPTION_HEADERS '
          '-DLINUXKPI_VERSION=70000 -DCONFIG_ATH12K_DEBUG -DKBUILD_MODNAME="ath12k"').split()
GPL_TEXT = re.compile(rb'SPDX-License-Identifier:[^\n]*GPL|GNU General Public License')


class Stop(Exception):
    """A gate failed: the message says which one."""


def read_pins(path=PINS):
    pins = {}
    for line in path.read_text().splitlines():
        if '=' in line and not line.startswith('#'):
            key, value = line.split('=', 1)
            pins[key.strip()] = value.strip()
    return pins


def tree_digest(root, part=''):
    """SHA-256 over sorted path and content of each file, independent of tar and of mtimes."""
    digest = hashlib.sha256()
    top = Path(root) / part
    names = []
    for folder, dirs, files in os.walk(top):
        dirs[:] = [d for d in dirs if d != '.git']
        names += [Path(folder) / f for f in files]
    for name in sorted(names, key=lambda p: p.relative_to(root).as_posix()):
        digest.update(name.relative_to(root).as_posix().encode() + b'\0')
        digest.update(hashlib.sha256(name.read_bytes()).digest())
    return digest.hexdigest()


def sparse_fetch(dest, url, pin, paths):
    """Partial clone of one commit; only `paths` reach the disk, and nothing fetched is ever run."""
    def git(*args):
        subprocess.run(['git', '-C', str(dest), *args], check=True)
    dest.mkdir(parents=True, exist_ok=True)
    git('init', '-q')
    git('config', 'core.autocrlf', 'false')
    git('remote', 'add', 'origin', url)
    git('config', 'remote.origin.promisor', 'true')
    git('config', 'remote.origin.partialclonefilter', 'blob:none')
    git('sparse-checkout', 'init', '--no-cone')
    git('sparse-checkout', 'set', '--no-cone', *paths)
    git('-c', 'protocol.version=2', 'fetch', '-q', '--filter=blob:none', '--no-tags', '--depth', '1', 'origin', pin)
    git('checkout', '-q', '--detach', 'FETCH_HEAD')


def check_pin(tree, sha, name):
    try:
        head = subprocess.run(['git', '-C', str(tree), 'rev-parse', 'HEAD'],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as error:
        raise Stop(f'pin: {tree} is not a checkout of {name}: {error}') from error
    if head != sha:
        raise Stop(f'pin: {tree} is at {head}, pins.env wants {sha}')


def license_gate(linux, sources):
    """Every compiled ath12k file names its license; only this directory may be used at all."""
    base = linux / ATH12K
    for rel in sources:
        path = base / rel
        if not path.is_file():
            raise Stop(f'license gate: {path} is missing')
        if SPDX not in path.read_text(errors='replace'):
            raise Stop(f'license gate: {rel} does not carry {SPDX}')


def refuse_linux_include(linux, include_dirs):
    """No directory of the Linux tree other than ath12k itself may be searched for headers."""
    linux = linux.resolve()
    base = (linux / ATH12K).resolve()
    for folder in include_dirs:
        real = Path(folder).resolve()
        if (real == linux or linux in real.parents) and real != base and base not in real.parents:
            raise Stop(f'license gate: Linux include path refused: {folder}')


def audit_dependencies(linux, edited_copy, allowed_roots, dep_files):
    """What the compiler really read: ath12k files with SPDX, FreeBSD and our own, no GPL text."""
    linux = linux.resolve()
    base = (linux / ATH12K).resolve()
    edited = Path(edited_copy).resolve()
    allowed = [Path(p).resolve() for p in allowed_roots]
    seen = set()
    for dep in dep_files:
        text = dep.read_text().replace('\\\n', ' ')
        for word in text.split(':', 1)[1].split():
            seen.add(word)
    for word in sorted(seen):
        real = Path(word).resolve()
        if real == linux or linux in real.parents:
            if base not in real.parents:
                raise Stop(f'license gate: read outside ath12k in Linux: {word}')
            if SPDX not in real.read_text(errors='replace'):
                raise Stop(f'license gate: {word} does not carry {SPDX}')
            continue
        if edited in real.parents and SPDX not in real.read_text(errors='replace'):
            raise Stop(f'license gate: {word} does not carry {SPDX}')
        if not any(root == real or root in real.parents for root in allowed):
            raise Stop(f'license gate: read outside the allowed trees: {word}')
        if GPL_TEXT.search(real.read_bytes()):
            raise Stop(f'license gate: GPL text in a header that was read: {word}')
    return len(seen)


def apply_edits(edits, source_of, target_of):
    """Each edit must find its text exactly once in the unedited-so-far file."""
    results = {}
    for edit in edits:
        key = (edit['tree'], edit['file'])
        if key not in results:
            results[key] = source_of(*key).read_bytes().decode()
        count = results[key].count(edit['find'])
        if count != 1:
            raise Stop(f"edit {edit['id']}: {edit['file']}: expected 1 match, found {count}")
        results[key] = results[key].replace(edit['find'], edit['replace'])
    for key, text in results.items():
        target = target_of(*key)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode())
    return len(edits)


def kobj_header(text):
    """Same declarations as makeobjops.awk -h, read from the .m text."""
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    interface = re.search(r'INTERFACE\s+(\w+)\s*;', text).group(1)
    out = [f'#ifndef _{interface}_if_h_', f'#define _{interface}_if_h_', '']
    position = 0
    token = re.compile(r'\b(HEADER|CODE)\s*\{|\b(STATICMETHOD|METHOD)\s+([^{;]+?)\s+(\w+)\s*\{')
    while True:
        match = token.search(text, position)
        if not match:
            break
        depth, index = 1, match.end()
        while depth:
            depth += {'{': 1, '}': -1}.get(text[index], 0)
            index += 1
        body = text[match.end():index - 1]
        position = index
        if match.group(1) == 'CODE':
            continue
        if match.group(1) == 'HEADER':
            out += [body, '']
            continue
        kind, result, name = match.group(2), ' '.join(match.group(3).split()), match.group(4)
        body = re.sub(r'\b(PRE|POST)\s*\{.*?\}\s*;?', '', body, flags=re.S)
        parts = [' '.join(p.split()) for p in body.split(';') if p.strip()]
        names = [re.search(r'(\w+)(\s*\[\s*\])?\s*$|\(\s*\*\s*(\w+)\s*\)', p) for p in parts]
        names = [m.group(1) or m.group(3) for m in names]
        declared = ', '.join(parts) or 'void'
        macro = f'{interface}_{name}'.upper()
        out += [f'extern struct kobjop_desc {interface}_{name}_desc;',
                f'typedef {result} {interface}_{name}_t({declared});',
                f'static __inline {result} {macro}({declared})', '{', '\tkobjop_t _m;']
        call_args = ', '.join(names)
        where = f'{names[0]}->ops' if kind == 'STATICMETHOD' else f'((kobj_t){names[0]})->ops'
        if result != 'void':
            out += [f'\t{result} rc;']
        out += [f'\tKOBJOPLOOKUP({where},{interface}_{name});']
        if result != 'void':
            out += [f'\trc = (({interface}_{name}_t *) _m)({call_args});', '\treturn (rc);', '}', '']
        else:
            out += [f'\t(({interface}_{name}_t *) _m)({call_args});', '}', '']
    out += ['#endif', '']
    return '\n'.join(out)


def generate(sysdir, gen):
    """What the FreeBSD kernel build would generate: kobj interfaces and option headers."""
    gen.mkdir(parents=True, exist_ok=True)
    machine = gen / 'machine'
    if not machine.exists():
        machine.symlink_to(sysdir / 'arm64/include', target_is_directory=True)
    for rel in KOBJ:
        source = sysdir / rel
        (gen / (source.stem + '.h')).write_text(kobj_header(source.read_text()))
    (gen / 'vnode_if.h').write_text('/* Nothing in this domain calls vnode operations. */\n')
    (gen / 'vnode_if_newproto.h').write_text('')
    (gen / 'vnode_if_typedef.h').write_text('')
    options = set()
    pattern = re.compile(rb'opt_[a-z0-9_]+\.h')
    for folder, _, files in os.walk(sysdir):
        for name in files:
            if name.endswith(('.h', '.m')):
                options.update(pattern.findall((Path(folder) / name).read_bytes()))
    for name in options:
        (gen / name.decode()).write_text('')
    (gen / 'lkpi_iic_if.h').write_text('')
    (gen / 'opt_inet.h').write_text('#define INET 1\n#define INET6 1\n')
    (gen / 'opt_inet6.h').write_text('#define INET6 1\n')
    (gen / 'opt_global.h').write_text('#define SMP 1\n')


class Toolchain:
    def __init__(self, args):
        self.darwin = platform.system() == 'Darwin'
        self.clang = args.cc or ('clang' if not self.darwin else
                                 subprocess.run(['xcrun', '--find', 'clang'], capture_output=True,
                                                text=True, check=True).stdout.strip())
        self.ld = shutil.which('ld') if self.darwin else None
        self.nm = args.nm or shutil.which('llvm-nm') or (
            subprocess.run(['xcrun', '--find', 'nm'], capture_output=True, text=True).stdout.strip())
        self.route = 'ld64' if self.ld else 'bitcode'
        if self.route == 'bitcode':
            for tool in ('llvm-link', 'opt', 'llc'):
                if not shutil.which(tool):
                    raise Stop(f'toolchain: no ld64 here and no {tool}: cannot make a Mach-O relocatable')


def compile_one(tool, source, output, flags):
    command = [tool.clang, '-target', TARGET, *flags, '-MMD', '-MF', str(output) + '.d', '-c', str(source)]
    command += ['-emit-llvm', '-o', str(output)] if tool.route == 'bitcode' else ['-o', str(output)]
    result = subprocess.run(command, capture_output=True, text=True)
    return source, output, result.returncode, result.stderr


def link(tool, objects, output, exported, work):
    if tool.route == 'ld64':
        listing = work / 'exported.txt'
        listing.write_text(''.join(f'_{name}\n' for name in exported))
        merged = work / 'all.o'
        subprocess.run([tool.ld, '-r', '-arch', 'arm64', *map(str, objects), '-o', str(merged)], check=True)
        subprocess.run([tool.ld, '-r', '-arch', 'arm64', '-exported_symbols_list', str(listing),
                        str(merged), '-o', str(output)], check=True)
        return
    merged = work / 'all.bc'
    subprocess.run(['llvm-link', *map(str, objects), '-o', str(merged)], check=True)
    internal = work / 'internal.bc'
    keep = ','.join(sorted(exported))
    # Internalize but keep everything, as ld -r does: dropping unreachable code would hide symbols.
    subprocess.run(['opt', '-passes=internalize', f'-internalize-public-api-list={keep}',
                    str(merged), '-o', str(internal)], check=True)
    subprocess.run(['llc', '-filetype=obj', '-O2', '--relocation-model=static', '-mtriple=' + TARGET,
                    '-mattr=-fp-armv8,-neon', str(internal), '-o', str(output)], check=True)


def symbols(tool, path, *flags):
    result = subprocess.run([tool.nm, *flags, str(path)], capture_output=True, text=True, check=True)
    return result.stdout.splitlines()


def check_undefined(names, allow):
    """Everything must be listed; nothing but the optional groups may be listed without being needed."""
    groups = {}
    allowed = {}
    optional = set()
    for group, members in allow['groups'].items():
        for member in members['symbols']:
            allowed[member] = group
            if members.get('optional'):
                optional.add(member)
    unknown = sorted(n for n in names if n not in allowed)
    for name in names:
        if name in allowed:
            groups.setdefault(allowed[name], []).append(name)
    stale = sorted(n for n in allowed if n not in names and n not in optional)
    return groups, unknown, stale


def strip_macho_prefix(name):
    return name[1:] if name.startswith('_') else name


def build(args):
    pins = read_pins()
    linux, freebsd = args.linux.resolve(), args.freebsd.resolve()
    if not args.no_pin_check:
        check_pin(linux, pins['ATH12K_LINUX_SHA'], 'Linux')
        check_pin(freebsd, pins['LKPI_FREEBSD_SHA'], 'FreeBSD')
        for key, tree, part in (('ATH12K_LINUX_TREE_SHA256', linux, ATH12K),
                                ('LKPI_FREEBSD_TREE_SHA256', freebsd, 'sys')):
            digest = tree_digest(tree, part)
            if digest != pins[key]:
                raise Stop(f'pin: {key} is {digest}, pins.env wants {pins[key]}')
    work = args.work.resolve()
    if work.exists() and args.clean:
        shutil.rmtree(work)
    if not args.clean:
        shutil.rmtree(work / 'src', ignore_errors=True)
        shutil.rmtree(work / 'overlay', ignore_errors=True)
    for sub in ('src', 'overlay', 'obj'):
        (work / sub).mkdir(parents=True, exist_ok=True)
    sysdir = freebsd / 'sys'

    if len(DRIVER) != 33:
        raise Stop(f'the design compiles 33 files, this script lists {len(DRIVER)}')
    license_gate(linux, DRIVER)

    src = work / 'src'
    shutil.copytree(linux / ATH12K, src, dirs_exist_ok=True)
    edits = json.loads(EDITS.read_text())['edits']
    def source_of(tree, rel):
        return (linux / ATH12K / rel) if tree == 'ath12k' else (freebsd / rel)
    def target_of(tree, rel):
        return (src / rel) if tree == 'ath12k' else (work / 'overlay' / rel.split('common/include/', 1)[1])
    applied = apply_edits(edits, source_of, target_of)

    generate(sysdir, work / 'gen')

    compat = OWN / 'compat'
    include_dirs = [work / 'overlay', compat / 'include', work / 'gen', sysdir, sysdir / 'contrib/ck/include',
                    sysdir / 'compat/linuxkpi/common/include', sysdir / 'compat/linuxkpi/dummy/include']
    refuse_linux_include(linux, include_dirs)
    flags = list(CFLAGS)
    flags += [f'-I{d}' for d in include_dirs]
    flags += ['-include', 'opt_global.h',
              '-include', str(sysdir / 'compat/linuxkpi/common/include/linux/kconfig.h'),
              '-include', str(compat / 'include/lx_prelude.h')]

    driver_flags = [*flags, f'-I{src}']
    own_flags = [*driver_flags, f'-I{OWN / "src"}', f'-I{compat}']
    jobs = []
    tool = Toolchain(args)
    suffix = '.bc' if tool.route == 'bitcode' else '.o'
    for rel in DRIVER:
        out = work / 'obj' / ('ath12k_' + rel.replace('/', '_').removesuffix('.c') + suffix)
        jobs.append((src / rel, out, driver_flags))
    own = sorted(compat.glob('*.c')) + sorted((OWN / 'src').glob('*.c'))
    for path in own:
        jobs.append((path, work / 'obj' / ('fa_' + path.stem + suffix), own_flags))

    failed = []
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        futures = [pool.submit(compile_one, tool, *job) for job in jobs]
        for future in concurrent.futures.as_completed(futures):
            source, output, code, stderr = future.result()
            (Path(str(output) + '.log')).write_text(stderr)
            if code:
                failed.append((source, stderr))
                output.unlink(missing_ok=True)
    if failed:
        for source, stderr in sorted(failed, key=lambda f: str(f[0])):
            errors = [l for l in stderr.splitlines() if ' error: ' in l or ' fatal error: ' in l]
            print(f'--- {source.name}: {len(errors)} errors')
            print('\n'.join(errors[:args.show]))
        names = ' '.join(sorted(s.name for s, _ in failed))
        raise Stop(f'compile: {len(failed)} of {len(jobs)} failed: {names}')

    allowed_roots = [work / 'src', work / 'overlay', work / 'gen', sysdir, compat, OWN / 'src']
    audit_dependencies(linux, src, allowed_roots,
                       [Path(str(job[1]) + '.d') for job in jobs])

    objects = [job[1] for job in jobs]
    allow = json.loads(ALLOW.read_text())
    exported = allow['exported']
    output = work / 'fuxi_ath12k.o'
    link(tool, objects, output, exported, work)
    kind = subprocess.run(['file', '-b', str(output)], capture_output=True, text=True).stdout.strip()
    if 'Mach-O 64-bit' not in kind or 'object' not in kind:
        raise Stop(f'link: not a Mach-O relocatable: {kind}')

    shown = sorted({strip_macho_prefix(line.strip()) for line in
                    symbols(tool, output, '--defined-only', '--extern-only', '--format=just-symbols')
                    if line.strip()})
    if shown != sorted(exported) or not all(name.startswith(EXPORTED_PREFIX) for name in shown):
        raise Stop(f'link: the object must show exactly {sorted(exported)}, it shows {shown}')

    raw = symbols(tool, output, '--undefined-only', '--format=just-symbols')
    undefined = sorted({strip_macho_prefix(line.strip()) for line in raw if line.strip()})
    (work / 'undefined.txt').write_text('\n'.join(undefined) + '\n')
    groups, unknown, stale = check_undefined(undefined, allow)
    if unknown:
        raise Stop('undefined: not on the allow-list: ' + ' '.join(unknown))
    if stale:
        raise Stop('undefined: on the allow-list but not needed: ' + ' '.join(stale))
    for group, names in sorted(groups.items()):
        print(f'undefined {group}: {len(names)}')
    if tool.route == 'bitcode':
        print('fuxi-ath12k: note: object made by llvm-link and llc, not ld -r: this host has no ld64')
    size = output.stat().st_size
    print(f'fuxi-ath12k: {len(DRIVER)} sources, object {size} bytes, undefined {len(undefined)}, all allowed')


def main():
    home = Path.home() / 'work'
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--linux', type=Path, default=home / 'ath12k-deps/linux')
    parser.add_argument('--freebsd', type=Path, default=home / 'ath12k-deps/freebsd')
    parser.add_argument('--work', type=Path, default=home / 'ath12k-build')
    parser.add_argument('--clean', action='store_true', help='remove the work directory first')
    parser.add_argument('--no-pin-check', action='store_true', help='for tests on fixture trees')
    parser.add_argument('--print-digests', action='store_true')
    parser.add_argument('--fetch', action='store_true', help='fetch the pinned sparse trees first, where absent')
    parser.add_argument('--cc')
    parser.add_argument('--nm')
    parser.add_argument('--jobs', type=int, default=os.cpu_count() or 4)
    parser.add_argument('--show', type=int, default=8, help='errors shown for each failed file')
    args = parser.parse_args()
    if args.print_digests:
        print('ATH12K_LINUX_TREE_SHA256=' + tree_digest(args.linux, ATH12K))
        print('LKPI_FREEBSD_TREE_SHA256=' + tree_digest(args.freebsd, 'sys'))
        return 0
    try:
        if args.fetch:
            pins = read_pins()
            if not args.linux.exists():
                sparse_fetch(args.linux, LINUX_URL, pins['ATH12K_LINUX_SHA'], LINUX_SPARSE)
            if not args.freebsd.exists():
                sparse_fetch(args.freebsd, FREEBSD_URL, pins['LKPI_FREEBSD_SHA'], FREEBSD_SPARSE)
        build(args)
    except Stop as stop:
        print(f'fuxi-ath12k: FAILED: {stop}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
